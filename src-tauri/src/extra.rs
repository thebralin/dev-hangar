// ---------------- TODO / FIXME scan ----------------

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct TodoHit {
    pub path: String,
    pub line: usize,
    pub kind: String,
    pub text: String,
}

pub fn scan_todos(paths: Vec<String>, limit: usize) -> Vec<TodoHit> {
    let re = Regex::new(r"\b(TODO|FIXME|HACK|XXX|BUG)\b[:(\s]").unwrap();
    let mut hits = vec![];
    for p in paths.iter().take(60) {
        let path = Path::new(p);
        let Ok(md) = fs::metadata(path) else { continue };
        if !md.is_file() || md.len() > 1_000_000 {
            continue;
        }
        let Ok(bytes) = fs::read(path) else { continue };
        if bytes[..bytes.len().min(8000)].contains(&0) {
            continue;
        }
        let text = String::from_utf8_lossy(&bytes);
        for (i, line) in text.lines().enumerate() {
            if let Some(m) = re.captures(line) {
                let kind = m.get(1).map(|x| x.as_str().to_string()).unwrap_or_default();
                let idx = m.get(0).map(|x| x.start()).unwrap_or(0);
                let t: String = line[idx..].trim().chars().take(200).collect();
                hits.push(TodoHit {
                    path: p.clone(),
                    line: i + 1,
                    kind,
                    text: t,
                });
                if hits.len() >= limit {
                    return hits;
                }
            }
        }
    }
    hits
}

// ---------------- file tree for AI context ----------------

const TREE_SKIP: &[&str] = &[
    ".git", "node_modules", "target", "dist", ".next", ".nuxt", ".output", ".astro", ".svelte-kit",
    ".turbo", ".cache", "coverage", "__pycache__", ".venv", "venv", ".vs", ".idea", ".vscode", "vendor",
];

pub fn file_tree(root: &str, max_depth: usize, max_entries: usize) -> String {
    let root_p = PathBuf::from(root);
    let walker = ignore::WalkBuilder::new(&root_p)
        .hidden(false)
        .require_git(false)
        .parents(false)
        .max_depth(Some(max_depth))
        .sort_by_file_path(|a, b| {
            // directories first, then by name
            let ad = a.is_dir();
            let bd = b.is_dir();
            if a.parent() == b.parent() && ad != bd {
                return bd.cmp(&ad);
            }
            a.to_string_lossy().to_lowercase().cmp(&b.to_string_lossy().to_lowercase())
        })
        .filter_entry(|e| {
            let n = e.file_name().to_string_lossy();
            !(e.depth() > 0 && TREE_SKIP.contains(&n.as_ref()))
        })
        .build();
    let mut out = String::new();
    let mut count = 0usize;
    let mut skipped = 0usize;
    for e in walker.flatten() {
        if e.depth() == 0 {
            continue;
        }
        if count >= max_entries {
            skipped += 1;
            continue;
        }
        let name = e.file_name().to_string_lossy();
        if name.ends_with(".lock") || name == "package-lock.json" || name == "pnpm-lock.yaml" || name == "yarn.lock" || name == "bun.lockb" {
            continue;
        }
        let is_dir = e.file_type().map(|t| t.is_dir()).unwrap_or(false);
        out.push_str(&"  ".repeat(e.depth() - 1));
        out.push_str(&name);
        if is_dir {
            out.push('/');
        }
        out.push('\n');
        count += 1;
    }
    if skipped > 0 {
        out.push_str(&format!("… и ещё {} элементов\n", skipped));
    }
    out
}

const AI_FILES: &[&str] = &["CLAUDE.md", "AGENTS.md", ".cursorrules", "GEMINI.md"];

pub fn write_ai_file(root: &str, name: &str, content: &str, overwrite: bool) -> Result<String, String> {
    if !AI_FILES.contains(&name) {
        return Err("Недопустимое имя файла".into());
    }
    let p = Path::new(root).join(name);
    if p.exists() && !overwrite {
        return Err("exists".into());
    }
    fs::write(&p, content).map_err(|e| e.to_string())?;
    Ok(p.to_string_lossy().to_string())
}

// ---------------- disk cleanup ----------------

#[derive(Serialize, Clone)]
#[serde(rename_all = "camelCase")]
pub struct ArtifactDir {
    pub path: String,
    pub rel: String,
    pub name: String,
    pub kind: String,
    pub size: u64,
    pub files: u64,
    pub modified: i64,
}

/// dirs that are always safe to delete (regenerated by install/build)
const ALWAYS: &[&str] = &[
    "node_modules", ".next", ".nuxt", ".output", ".astro", ".svelte-kit", ".turbo", ".parcel-cache",
    ".vite", ".angular", ".expo",
];
/// build outputs: only when a package.json sits next to them
const JS_BUILD: &[&str] = &["dist", "build", "out", "dist-electron", "release"];

pub fn deletable_name(name: &str) -> bool {
    ALWAYS.contains(&name) || JS_BUILD.contains(&name) || name == "target" || name == ".venv" || name == "venv" || name == "vendor"
}

fn classify(dir: &Path, name: &str) -> Option<&'static str> {
    let parent = dir.parent()?;
    if ALWAYS.contains(&name) {
        return Some(if name == "node_modules" { "deps" } else { "cache" });
    }
    if JS_BUILD.contains(&name) && parent.join("package.json").exists() {
        return Some("build");
    }
    if name == "target" && parent.join("Cargo.toml").exists() {
        return Some("build");
    }
    if (name == ".venv" || name == "venv") && dir.join("pyvenv.cfg").exists() {
        return Some("deps");
    }
    // composer's vendor (restored by `composer install`); Go's vendor/ has no composer.json next to it
    if name == "vendor" && parent.join("composer.json").exists() && dir.join("autoload.php").exists() {
        return Some("deps");
    }
    None
}

fn dir_size(p: &Path, size: &mut u64, files: &mut u64, newest: &mut i64) {
    let Ok(rd) = fs::read_dir(p) else { return };
    for e in rd.flatten() {
        let Ok(md) = e.path().symlink_metadata() else { continue };
        if md.file_type().is_symlink() {
            continue;
        }
        if md.is_dir() {
            dir_size(&e.path(), size, files, newest);
        } else {
            *size += md.len();
            *files += 1;
        }
    }
    if let Ok(md) = fs::metadata(p) {
        if let Ok(m) = md.modified() {
            *newest = (*newest).max(to_millis(m));
        }
    }
}

pub fn scan_artifacts(root: &str) -> Vec<ArtifactDir> {
    let root_p = PathBuf::from(root);
    let mut out = vec![];
    fn walk(root: &Path, dir: &Path, depth: usize, out: &mut Vec<ArtifactDir>) {
        if depth > 4 {
            return;
        }
        let Ok(rd) = fs::read_dir(dir) else { return };
        for e in rd.flatten() {
            let Ok(ft) = e.file_type() else { continue };
            if !ft.is_dir() || ft.is_symlink() {
                continue;
            }
            let name = e.file_name().to_string_lossy().to_string();
            if name == ".git" {
                continue;
            }
            let p = e.path();
            if let Some(kind) = classify(&p, &name) {
                let (mut size, mut files, mut newest) = (0u64, 0u64, 0i64);
                dir_size(&p, &mut size, &mut files, &mut newest);
                out.push(ArtifactDir {
                    path: p.to_string_lossy().to_string(),
                    rel: rel(root, &p),
                    name,
                    kind: kind.to_string(),
                    size,
                    files,
                    modified: newest,
                });
                continue;
            }
            if name.starts_with('.') {
                continue;
            }
            walk(root, &p, depth + 1, out);
        }
    }
    walk(&root_p, &root_p, 1, &mut out);
    out.sort_by(|a, b| b.size.cmp(&a.size));
    out
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct DeleteResult {
    pub path: String,
    pub ok: bool,
    pub error: Option<String>,
}

fn clear_readonly(p: &Path) {
    if let Ok(rd) = fs::read_dir(p) {
        for e in rd.flatten() {
            let path = e.path();
            if let Ok(md) = path.symlink_metadata() {
                if md.is_dir() && !md.file_type().is_symlink() {
                    clear_readonly(&path);
                }
                let mut perm = md.permissions();
                if perm.readonly() {
                    #[allow(clippy::permissions_set_readonly_false)]
                    perm.set_readonly(false);
                    let _ = fs::set_permissions(&path, perm);
                }
            }
        }
    }
}

pub fn delete_artifacts(roots: Vec<String>, paths: Vec<String>) -> Vec<DeleteResult> {
    let norm = |s: &str| s.replace('\\', "/").trim_end_matches('/').to_lowercase();
    let roots_n: Vec<String> = roots.iter().map(|r| norm(r)).collect();
    paths
        .into_iter()
        .map(|p| {
            let path = PathBuf::from(&p);
            let name = path.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default();
            let pn = norm(&p);
            let inside = roots_n.iter().any(|r| pn.starts_with(&format!("{}/", r)));
            if !deletable_name(&name) || !inside {
                return DeleteResult { path: p, ok: false, error: Some("Папка не из списка разрешённых".into()) };
            }
            let mut res = fs::remove_dir_all(&path);
            if res.is_err() && path.exists() {
                clear_readonly(&path);
                res = fs::remove_dir_all(&path);
            }
            match res {
                Ok(_) => DeleteResult { path: p, ok: true, error: None },
                Err(e) => DeleteResult { path: p, ok: false, error: Some(e.to_string()) },
            }
        })
        .collect()
}
